package dev.jonpoulton.catalog.gradle.internal.writer

import com.squareup.kotlinpoet.Annotatable
import com.squareup.kotlinpoet.ClassName
import com.squareup.kotlinpoet.Documentable
import com.squareup.kotlinpoet.FileSpec
import com.squareup.kotlinpoet.FunSpec
import com.squareup.kotlinpoet.KModifier
import com.squareup.kotlinpoet.MemberName
import com.squareup.kotlinpoet.PropertySpec
import com.squareup.kotlinpoet.TypeSpec
import dev.jonpoulton.catalog.gradle.GenerateResourcesTask
import dev.jonpoulton.catalog.gradle.internal.ResourceEntry
import dev.jonpoulton.catalog.gradle.internal.ResourceType
import java.io.File

internal abstract class CatalogWriter<T : ResourceEntry> {
  protected abstract val config: GenerateResourcesTask.TaskConfig
  protected abstract val resourceType: ResourceType

  protected val rClass by lazy { config.resClass }

  protected val composableClass = ClassName("androidx.compose.runtime", "Composable")
  private val readOnlyComposableClass = ClassName("androidx.compose.runtime", "ReadOnlyComposable")

  private val className: String
    get() = "${config.typePrefix}${resourceType.receiverType}"

  fun write(resources: List<T>, codegenDestination: File) {
    val perFile = config.extensionsPerFile
    if (perFile == null) {
      writeObject(resources, codegenDestination)
    } else {
      writeExtensions(resources, codegenDestination, perFile)
    }
  }

  private fun writeObject(resources: List<T>, codegenDestination: File) {
    val type = TypeSpec.objectBuilder(className).addInternalIfConfigured()
    resources.forEachWrapped { resource ->
      when (val member = buildMember(resource, receiver = null)) {
        is Member.Property -> type.addProperty(member.spec)
        is Member.Function -> type.addFunction(member.spec)
      }
    }
    fileSpecBuilder(className).addType(type.build()).build().writeTo(codegenDestination)
  }

  private fun writeExtensions(resources: List<T>, codegenDestination: File, perFile: Int) {
    require(perFile > 0) { "maxExtensionsPerFile must be positive, got $perFile" }

    val type = TypeSpec.objectBuilder(className).addInternalIfConfigured().build()
    fileSpecBuilder(className).addType(type).build().writeTo(codegenDestination)

    val receiver = ClassName(config.packageName, className)
    resources.chunked(perFile).forEachIndexed { index, chunk ->
      val file = fileSpecBuilder("${className}Ext${index + 1}")
      chunk.forEachWrapped { resource ->
        when (val member = buildMember(resource, receiver)) {
          is Member.Property -> file.addProperty(member.spec)
          is Member.Function -> file.addFunction(member.spec)
        }
      }
      file.build().writeTo(codegenDestination)
    }
  }

  /** Builds the accessor for [resource]. When [receiver] is set, it's an extension on that type. */
  abstract fun buildMember(resource: T, receiver: ClassName?): Member

  internal sealed interface Member {
    data class Property(val spec: PropertySpec) : Member

    data class Function(val spec: FunSpec) : Member
  }

  private fun fileSpecBuilder(fileName: String): FileSpec.Builder =
    FileSpec.builder(config.packageName, fileName)
      .addFileComment("DO NOT EDIT: Auto-generated by Catalog. https://github.com/jonapoul/catalog")

  @Suppress("TooGenericExceptionCaught")
  private fun List<T>.forEachWrapped(action: (T) -> Unit) {
    forEach { resource ->
      try {
        action(resource)
      } catch (e: Exception) {
        throw IllegalStateException(
          "Error writing resource \"${resource.name}\" in ${resource.file}",
          e,
        )
      }
    }
  }

  protected fun <T : Documentable.Builder<T>> Documentable.Builder<T>.addKdoc(
    item: ResourceEntry.XmlItem,
  ): T {
    item.docs?.let { addKdoc(it) }
    @Suppress("UNCHECKED_CAST")
    return this as T
  }

  protected fun <T : Annotatable.Builder<T>> Annotatable.Builder<T>.addReadOnlyComposable(
    config: GenerateResourcesTask.TaskConfig,
  ): T =
    if (config.useReadOnlyComposable) {
      addAnnotation(readOnlyComposableClass)
    } else {
      @Suppress("UNCHECKED_CAST")
      this as T
    }

  protected fun resourceAccessor(name: String): MemberName =
    MemberName(config.composableResourceAccessorPackage, name)

  protected fun <T> T.addInternalIfConfigured(): T {
    if (config.generateInternal) {
      when (this) {
        is FunSpec.Builder -> addModifiers(KModifier.INTERNAL)
        is PropertySpec.Builder -> addModifiers(KModifier.INTERNAL)
        is TypeSpec.Builder -> addModifiers(KModifier.INTERNAL)
      }
    }
    return this
  }
}

internal fun PropertySpec.Builder.receiverIfSet(receiver: ClassName?): PropertySpec.Builder =
  apply {
    receiver?.let { receiver(it) }
  }

internal fun FunSpec.Builder.receiverIfSet(receiver: ClassName?): FunSpec.Builder = apply {
  receiver?.let { receiver(it) }
}
